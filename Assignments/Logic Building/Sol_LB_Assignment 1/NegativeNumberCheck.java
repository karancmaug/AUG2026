public class NegativeNumberCheck {
    public static void main(String[] args) {
        
     
        int number = -8; 
        if (number < 0) {
            
            System.out.println("The number " + number + " is negative.");
        } else {
            
            System.out.println("The number " + number + " is not negative.");
        }
        
    }
}