public class GoodMorningMessage {
    public static void main(String[] args) {
        
        // 1. Define the predefined time (using 24-hour format
        int time = 9; 

        // 2. Use an if statement to check the condition
        // The condition checks if the time is 5 or greater, AND strictly less than 12
        if (time >= 5 && time < 12) {
            System.out.println("Good Morning");
        }
        
    }
}